    private val byCode: Map<String, DtcEntry> = entries.associateBy { it.code }
    private val validCodeRegex = Regex("^[PCBU][0-9A-F]{4}$")

    fun decode(rawCode: String): DecodedDtc {
        val code = rawCode.trim().uppercase()
        byCode[code]?.let {
            return DecodedDtc(it.code, it.titleUk, it.detailsUk, it.severity, it.subsystemUk)
        }

        if (code.length < 2) {
            return DecodedDtc(
                code = code.ifEmpty { "—" },
                titleUk = "Невідомий код помилки",
                detailsUk = "Некоректний формат коду діагностики.",
                severity = DtcSeverity.INFO,
                subsystemUk = "Загальна діагностика"
            )
        }

        val subsystem = when (code[0]) {
            'P' -> when (code.getOrNull(2)) {
                '0', '1', '2' -> "Повітря та паливо"
                '3' -> "Запалювання"
                '4' -> "Екологія / Випуск"
                '5' -> "Швидкість / ХХ"
                '6' -> "Живлення / ЕБУ"
                '7', '8', '9' -> "Трансмісія"
                'A', 'B', 'C' -> "48V Гібрид"
                else -> "Силова установка (ДВЗ)"
            }
            'C' -> "Шасі / ABS / ESP"
            'B' -> "Кузовна електроніка"
            'U' -> "Мережа CAN"
            else -> "Діагностика"
        }

        val originNote = if (code.getOrNull(1) == '1' || code.getOrNull(1) == '2' || code.getOrNull(1) == '3') {
            "Заводський код виробника (Suzuki). Рекомендується сканування дилерським сканером SZ Viewer."
        } else {
            "Стандартний код SAE J2012. Перевірте вузол підсистеми «$subsystem»."
        }

        val prefixName = when (code[0]) {
            'P' -> "Силова установка"
            'C' -> "Шасі та гальма"
            'B' -> "Кузов та комфорт"
            'U' -> "Шина зв'язку CAN"
            else -> "Система авто"
        }

        return DecodedDtc(
            code = code,
            titleUk = "Код $code ($prefixName)",
            detailsUk = originNote,
            severity = if (code[0] == 'P' || code[0] == 'C') DtcSeverity.WARNING else DtcSeverity.INFO,
            subsystemUk = subsystem
        )
    }

    fun search(query: String, limit: Int = 25): List<DecodedDtc> {
        val q = query.trim().uppercase()
        if (q.isEmpty()) {
            return entries.take(limit).map {
                DecodedDtc(it.code, it.titleUk, it.detailsUk, it.severity, it.subsystemUk)
            }
        }

        val matched = entries.asSequence()
            .filter { e ->
                e.code.contains(q) ||
                    e.titleUk.uppercase().contains(q) ||
                    e.detailsUk.uppercase().contains(q) ||
                    e.subsystemUk.uppercase().contains(q)
            }
            .take(limit)
            .map { DecodedDtc(it.code, it.titleUk, it.detailsUk, it.severity, it.subsystemUk) }
            .toMutableList()

        if (validCodeRegex.matches(q) && matched.none { it.code == q }) {
            matched.add(0, decode(q))
        }
        return matched
    }
